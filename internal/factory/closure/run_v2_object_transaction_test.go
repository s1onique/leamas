func TestV2CanonicalArtifactsStableAndSanitized(t *testing.T) {
	input := canonicalArtifactTestInput()
	first, err := generateV2CanonicalArtifacts(input)
	if err != nil {
		t.Fatal(err)
	}
	second, err := generateV2CanonicalArtifacts(input)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(first, second) {
		t.Fatal("canonical artifacts changed across identical runs")
	}
	if len(first.ManifestBytes) == 0 || first.ManifestBytes[len(first.ManifestBytes)-1] != '\n' ||
		len(first.ReportBytes) == 0 || first.ReportBytes[len(first.ReportBytes)-1] != '\n' {
		t.Fatal("canonical artifacts must end in one deterministic newline")
	}
	if first.ManifestSHA256 != SHA256Hex(first.ManifestBytes) || first.ReportSHA256 != SHA256Hex(first.ReportBytes) {
		t.Fatal("artifact SHA-256 does not bind generated bytes")
	}
	forbiddenFields := []string{
		"started_at_utc", "finished_at_utc", "duration_ms", "detached_evidence",
		"evidence_path", "TO_BE_FILLED", "leamas_version", "binary_sha256", "branch",
		"stdout_sha256", "stderr_sha256", "stdout_byte_count", "stderr_byte_count",
		"output_bytes_observed",
	}
	for _, forbidden := range forbiddenFields {
		if bytes.Contains(first.ManifestBytes, []byte(forbidden)) || bytes.Contains(first.ReportBytes, []byte(forbidden)) {
			t.Fatalf("canonical artifacts contain unstable or forbidden field %q", forbidden)
		}
	}
	var manifest map[string]any
	if err := json.Unmarshal(first.ManifestBytes, &manifest); err != nil {
		t.Fatal(err)
	}
	if manifest["contract_version"] != float64(1) || manifest["closure_protocol_version"] != float64(2) {
		t.Fatalf("version fields = %#v", manifest)
	}
}

func TestV2CanonicalArtifactsIgnoreAmbientClock(t *testing.T) {
	input := canonicalArtifactTestInput()
	first, err := generateV2CanonicalArtifacts(input)
	if err != nil {
		t.Fatal(err)
	}
	time.Sleep(time.Millisecond)
	second, err := generateV2CanonicalArtifacts(input)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first.ManifestBytes, second.ManifestBytes) || !bytes.Equal(first.ReportBytes, second.ReportBytes) {
		t.Fatal("ambient clock affected canonical artifact bytes")
	}
}

func TestBuildV2ClosureObjectsGeometryAndDeterminism(t *testing.T) {
	for _, objectFormat := range supportedObjectFormats(t) {
		t.Run(string(objectFormat), func(t *testing.T) {
			repo, subject, subjectTree := prepareObjectTransactionRepository(t, objectFormat)
			artifacts := mustCanonicalArtifacts(t)
			indexBefore := readRealIndex(t, repo)

			result, err := buildV2ClosureObjects(context.Background(), RealGit{}, repo, objectFormat, subject, subjectTree, objectTransactionActID, artifacts)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(indexBefore, readRealIndex(t, repo)) {
				t.Fatal("alternate-index construction changed the real index")
			}
			assertObjectTransactionResult(t, repo, objectFormat, subject, subjectTree, artifacts, result)

			v2Git(t, repo, "config", "user.name", "Ambient Other")
			v2Git(t, repo, "config", "user.email", "ambient-other@example.invalid")
			again, err := buildV2ClosureObjects(context.Background(), RealGit{}, repo, objectFormat, subject, subjectTree, objectTransactionActID, artifacts)
			if err != nil {
				t.Fatal(err)
			}
			if result != again {
				t.Fatalf("ambient Git identity changed object result: first=%+v second=%+v", result, again)
			}
		})
	}
}

func TestBuildV2ClosureObjectsRejectsPreExistingCanonicalPath(t *testing.T) {
	repo, subject, subjectTree := prepareObjectTransactionRepository(t, ObjectFormatSHA1)
	path := filepath.Join(repo, canonicalV2ManifestPath(objectTransactionActID))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte("existing\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	v2Git(t, repo, "add", canonicalV2ManifestPath(objectTransactionActID))
	v2Git(t, repo, "commit", "-m", "pre-existing canonical path")
	subject = v2Git(t, repo, "rev-parse", "HEAD")
	subjectTree = v2Git(t, repo, "rev-parse", "HEAD^{tree}")
	_, err := buildV2ClosureObjects(context.Background(), RealGit{}, repo, ObjectFormatSHA1, subject, subjectTree, objectTransactionActID, mustCanonicalArtifacts(t))
	if err == nil || !strings.Contains(err.Error(), "already exists") {
		t.Fatalf("expected pre-existing path rejection, got %v", err)
	}
}

func TestBuildV2ClosureObjectsFailureWindowsAreIsolated(t *testing.T) {
	windows := []struct {
		name       string
		command    string
		occurrence int
	}{
		{name: "read-tree", command: "read-tree", occurrence: 1},
		{name: "first update-index", command: "update-index", occurrence: 1},
		{name: "second update-index", command: "update-index", occurrence: 2},
		{name: "write-tree", command: "write-tree", occurrence: 1},
	}
	for _, window := range windows {
		t.Run(window.name, func(t *testing.T) {
			repo, subject, subjectTree := prepareObjectTransactionRepository(t, ObjectFormatSHA1)
			before := captureRepositoryWindow(t, repo)
			git := &recordingIndexGit{
				delegate: RealGit{}, failCommand: window.command,
				failOccurrence: window.occurrence,
			}
			_, err := buildV2ClosureObjects(context.Background(), git, repo, ObjectFormatSHA1,
				subject, subjectTree, objectTransactionActID, mustCanonicalArtifacts(t))
			if err == nil {
				t.Fatalf("expected injected %s failure", window.name)
			}
			if git.indexPath == "" {
				t.Fatal("no alternate index was observed")
			}
			if _, statErr := os.Lstat(git.indexPath); !errors.Is(statErr, os.ErrNotExist) {
				t.Fatalf("temporary index remains after failure: %v", statErr)
			}
			assertRepositoryWindowEqual(t, before, captureRepositoryWindow(t, repo))
		})
	}
}

