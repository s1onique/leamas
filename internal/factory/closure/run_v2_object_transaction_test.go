func supportedObjectFormats(t *testing.T) []ObjectFormat {
	t.Helper()
	formats := []ObjectFormat{ObjectFormatSHA1}
	probe := t.TempDir()
	result := RealGit{}.Run(context.Background(), probe, "init", "--object-format=sha256")
	if result.Err == nil && result.ExitCode == 0 {
		formats = append(formats, ObjectFormatSHA256)
	}
	return formats
}

func prepareObjectTransactionRepository(t *testing.T, objectFormat ObjectFormat) (string, string, string) {
	t.Helper()
	repo := t.TempDir()
	args := []string{"init", "-b", "main"}
	if objectFormat == ObjectFormatSHA256 {
		args = append(args, "--object-format=sha256")
	}
	v2Git(t, repo, args...)
	v2Git(t, repo, "config", "user.name", "Ambient User")
	v2Git(t, repo, "config", "user.email", "ambient@example.invalid")
	if err := os.WriteFile(filepath.Join(repo, "README.md"), []byte("subject\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	v2Git(t, repo, "add", "README.md")
	v2Git(t, repo, "commit", "-m", "subject")
	return repo, v2Git(t, repo, "rev-parse", "HEAD"), v2Git(t, repo, "rev-parse", "HEAD^{tree}")
}

type repositoryWindow struct {
	index  []byte
	status []byte
	head   []byte
	refs   []byte
}

func captureRepositoryWindow(t *testing.T, repo string) repositoryWindow {
	t.Helper()
	return repositoryWindow{
		index:  readRealIndex(t, repo),
		status: rawGitStdout(t, repo, "status", "--porcelain=v1", "--untracked-files=normal"),
		head:   rawGitStdout(t, repo, "rev-parse", "HEAD"),
		refs:   rawGitStdout(t, repo, "for-each-ref", "--format=%(refname)%00%(objectname)"),
	}
}

func assertRepositoryWindowEqual(t *testing.T, want, got repositoryWindow) {
	t.Helper()
	if !reflect.DeepEqual(want, got) {
		t.Fatalf("repository state changed across failed object transaction:\nwant=%q\ngot=%q", want, got)
	}
}

func readRealIndex(t *testing.T, repo string) []byte {
	t.Helper()
	gitDir := v2Git(t, repo, "rev-parse", "--git-dir")
	if !filepath.IsAbs(gitDir) {
		gitDir = filepath.Join(repo, gitDir)
	}
	data, err := os.ReadFile(filepath.Join(gitDir, "index"))
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func assertObjectTransactionResult(t *testing.T, repo string, format ObjectFormat, subject, subjectTree string, artifacts v2CanonicalArtifacts, result v2ClosureObjects) {
	t.Helper()
	if err := ValidateOIDWithFormat("closure tree", result.TreeOID, format); err != nil {
		t.Fatal(err)
	}
	if err := ValidateOIDWithFormat("closure commit", result.CommitOID, format); err != nil {
		t.Fatal(err)
	}
	manifestPath := canonicalV2ManifestPath(objectTransactionActID)
	reportPath := canonicalV2ReportPath(objectTransactionActID)
	diff := v2Git(t, repo, "diff-tree", "--no-commit-id", "--name-status", "-r", subjectTree, result.TreeOID)
	wantDiff := "A\t" + reportPath + "\nA\t" + manifestPath
	if diff != wantDiff {
		t.Fatalf("tree diff = %q, want %q", diff, wantDiff)
	}
	if got := v2Git(t, repo, "rev-parse", result.TreeOID+":"+manifestPath); got != result.ManifestBlobOID {
		t.Fatalf("manifest tree blob = %s, want %s", got, result.ManifestBlobOID)
	}
	if got := v2Git(t, repo, "rev-parse", result.TreeOID+":"+reportPath); got != result.ReportBlobOID {
		t.Fatalf("report tree blob = %s, want %s", got, result.ReportBlobOID)
	}
	if got := rawGitStdout(t, repo, "cat-file", "blob", result.ManifestBlobOID); !bytes.Equal(got, artifacts.ManifestBytes) {
		t.Fatal("manifest blob bytes do not exactly match generated bytes")
	}
	if got := rawGitStdout(t, repo, "cat-file", "blob", result.ReportBlobOID); !bytes.Equal(got, artifacts.ReportBytes) {
		t.Fatal("report blob bytes do not exactly match generated bytes")
	}
	parents := strings.Fields(v2Git(t, repo, "rev-list", "--parents", "-n", "1", result.CommitOID))
	if len(parents) != 2 || parents[1] != subject {
		t.Fatalf("closure parents = %v, want exactly %s", parents, subject)
	}
	subjectEpoch := v2Git(t, repo, "show", "-s", "--format=%ct", subject)
	closureEpoch := v2Git(t, repo, "show", "-s", "--format=%ct", result.CommitOID)
	if closureEpoch != incrementDecimalEpoch(t, subjectEpoch) {
		t.Fatalf("closure epoch = %s, want subject+1", closureEpoch)
	}
}

func rawGitStdout(t *testing.T, repo string, args ...string) []byte {
	t.Helper()
	result := RealGit{}.Run(context.Background(), repo, args...)
	if result.Err != nil || result.ExitCode != 0 {
		t.Fatalf("git %v: %v (exit %d): %s", args, result.Err, result.ExitCode, result.Stderr)
	}
	return append([]byte(nil), result.Stdout...)
}

func incrementDecimalEpoch(t *testing.T, raw string) string {
	t.Helper()
	parsed, err := strconv.ParseInt(raw, 10, 64)
	if err != nil {
		t.Fatal(err)
	}
	return strconv.FormatInt(parsed+1, 10)
}

type recordingIndexGit struct {
	delegate       RealGit
	failCommand    string
	failOccurrence int
	commandCalls   map[string]int
	indexPath      string
}

func (g *recordingIndexGit) Run(ctx context.Context, dir string, args ...string) gitCommandResult {
	return g.delegate.Run(ctx, dir, args...)
}

func (g *recordingIndexGit) RunWithStdin(ctx context.Context, dir, stdin string, args ...string) gitCommandResult {
	return g.delegate.RunWithStdin(ctx, dir, stdin, args...)
}

func (g *recordingIndexGit) RunWithStdinAndEnv(ctx context.Context, dir, stdin string, env []string, args ...string) gitCommandResult {
	return g.delegate.RunWithStdinAndEnv(ctx, dir, stdin, env, args...)
}

func (g *recordingIndexGit) RunWithEnv(ctx context.Context, dir string, env []string, args ...string) gitCommandResult {
	for _, item := range env {
		if strings.HasPrefix(item, "GIT_INDEX_FILE=") {
			g.indexPath = strings.TrimPrefix(item, "GIT_INDEX_FILE=")
		}
	}
	if len(args) > 0 {
		if g.commandCalls == nil {
			g.commandCalls = make(map[string]int)
		}
		g.commandCalls[args[0]]++
		occurrence := g.failOccurrence
		if occurrence == 0 {
			occurrence = 1
		}
		if args[0] == g.failCommand && g.commandCalls[args[0]] == occurrence {
			return gitCommandResult{ExitCode: 1, Err: errors.New("injected failure"), Stderr: []byte("injected failure")}
		}
	}
	return g.delegate.RunWithEnv(ctx, dir, env, args...)
}
